const { contextBridge, ipcRenderer } = require('electron')

contextBridge.exposeInMainWorld('electronAPI', {
  isElectron: true,
  runTweak: (key, arg) => ipcRenderer.invoke('run-tweak', key, arg),
  getAdminStatus: () => ipcRenderer.invoke('get-admin-status'),
  onAdminStatus: (cb) => { ipcRenderer.removeAllListeners('admin-status'); ipcRenderer.on('admin-status', (_, val) => cb(val)) },
  getSystemInfo: () => ipcRenderer.invoke('get-system-info'),
  getHardwareProfile: () => ipcRenderer.invoke('get-hardware-profile'),
  refreshHardwareProfile: () => ipcRenderer.invoke('refresh-hardware-profile'),
  getMemoryInfo: () => ipcRenderer.invoke('get-memory-info'),
  getStartupItems: () => ipcRenderer.invoke('get-startup-items'),
  getProcesses: () => ipcRenderer.invoke('get-processes'),
  getProcessCount: () => ipcRenderer.invoke('get-process-count'),
  getPersistentState: () => ipcRenderer.invoke('persistent-state-get'),
  setPersistentStateKey: (key, value) => ipcRenderer.invoke('persistent-state-set', key, value),
  deletePersistentStateKey: (key) => ipcRenderer.invoke('persistent-state-delete', key),
  mergePersistentState: (data) => ipcRenderer.invoke('persistent-state-merge', data),
  backupCreate: (name) => ipcRenderer.invoke('backup-create', name),
  backupList: () => ipcRenderer.invoke('backup-list'),
  backupRestore: (fp) => ipcRenderer.invoke('backup-restore', fp),
  createRestorePoint: (name) => ipcRenderer.invoke('create-restore-point', name),
  listRestorePoints: () => ipcRenderer.invoke('restore-point-list'),
  restoreToPoint: (sequenceNumber) => ipcRenderer.invoke('restore-point-apply', sequenceNumber),
  runScan: () => ipcRenderer.invoke('run-scan'),
  runFirmwareScan: () => ipcRenderer.invoke('firmware-scan'),
  pingTest: () => ipcRenderer.invoke('ping-test'),
  getPowerPlans: () => ipcRenderer.invoke('power-plans-list'),
  setPowerPlan: (guid) => ipcRenderer.invoke('power-plan-set', guid),
  ensureUltimatePowerPlan: () => ipcRenderer.invoke('power-plan-ensure-ultimate'),
  activateUltimatePowerPlan: () => ipcRenderer.invoke('power-plan-activate-ultimate'),
  revertDefaultPowerPlan: () => ipcRenderer.invoke('power-plan-revert-default'),
  getDeviceId: () => ipcRenderer.invoke('get-device-id'),
  verifyLicense: (key) => ipcRenderer.invoke('verify-license', key),
  getLicenseStatus: () => ipcRenderer.invoke('get-license-status'),
  clearLicenseStatus: () => ipcRenderer.invoke('clear-license-status'),
  deactivateLicense: () => ipcRenderer.invoke('deactivate-license'),
  debugLicenseInfo: () => ipcRenderer.invoke('debug-license-info'),
  toolLogin: (payload) => ipcRenderer.invoke('tool-login', payload),
  toolOAuthLogin: (payload) => ipcRenderer.invoke('tool-oauth-login', payload),
  toolLogout: () => ipcRenderer.invoke('tool-logout'),
  toolVerifyAccess: () => ipcRenderer.invoke('tool-verify-access'),
  startToolOAuth: (provider) => ipcRenderer.invoke('tool-start-oauth', provider),
  onToolOAuthCode: (cb) => { const listener = (_, data) => cb(data); ipcRenderer.on('tool-oauth-code', listener); return () => ipcRenderer.removeListener('tool-oauth-code', listener) },
  onSplashStatus: (cb) => { ipcRenderer.removeAllListeners('splash-status'); ipcRenderer.on('splash-status', (_, data) => cb(data)) },
  splashAction: (action) => ipcRenderer.send('splash-action', action),
  getLatestUpdateStatus: () => ipcRenderer.invoke('get-latest-update-status'),
  checkForUpdates: () => ipcRenderer.invoke('check-for-updates'),
  downloadUpdate: () => ipcRenderer.invoke('download-update'),
  installUpdate: () => ipcRenderer.invoke('install-update'),
  onUpdateStatus: (cb) => { ipcRenderer.removeAllListeners('update-status'); ipcRenderer.on('update-status', (_, data) => cb(data)) },
  openExternal: (url) => ipcRenderer.invoke('open-external', url),
  minimize: () => ipcRenderer.send('win-minimize'),
  maximize: () => ipcRenderer.send('win-maximize'),
  close: () => ipcRenderer.send('win-close'),
})

